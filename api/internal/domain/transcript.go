// Package domain defines the core business entities of the application.
package domain

import "time"

// TranscriptCue is a raw subtitle line exactly as extracted from a YouTube
// video or read from an uploaded transcript. Cues are never rewritten.
type TranscriptCue struct {
	ID      string `json:"id"`
	VideoID string `json:"video_id"`
	Seq     int    `json:"seq"`
	StartMs int64  `json:"start_ms"`
	EndMs   int64  `json:"end_ms"`
	Text    string `json:"text"`
}

// Transcript is the normalized transcript of a video: one per video, produced
// by YouTube subtitle extraction or a direct upload. Raw cues live in
// transcript_cues and are never rewritten.
type Transcript struct {
	ID               string           `json:"id"`
	VideoID          string           `json:"video_id"`
	ExtractionMethod ExtractionMethod `json:"extraction_method"`
	OriginalFormat   string           `json:"original_format"`
	Language         *string          `json:"language,omitempty"`
	ArtifactKey      *string          `json:"artifact_key,omitempty"`
	CueCount         int              `json:"cue_count"`
	CreatedAt        time.Time        `json:"created_at"`
}

type ExtractionMethod string

const (
	ExtractionManualSubtitle ExtractionMethod = "manual_subtitle"
	ExtractionAutoGenerated  ExtractionMethod = "auto_generated"
	ExtractionDirectUpload   ExtractionMethod = "direct_upload"
)

// TranscriptChunk is an indexed search chunk produced by later processing
// (deduped, sentence-normalized, possibly spanning several cues). Kept as a
// separate entity so raw cues stay immutable.
type TranscriptChunk struct {
	ID        string    `json:"id"`
	VideoID   string    `json:"video_id"`
	StartMs   int64     `json:"start_ms"`
	EndMs     int64     `json:"end_ms"`
	Text      string    `json:"text"`
	CreatedAt time.Time `json:"created_at"`
}
